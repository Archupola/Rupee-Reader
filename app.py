"""
app.py - Rupee Reader Streamlit app.

AI-Based Indian Currency Recognition & Voice Assistant.
Accessibility-focused prototype for visually impaired / low-vision users.
"""

import glob
import os

import streamlit as st
import streamlit.components.v1 as components

from predict import Predictor, load_model_info, model_available
from utils.speech import phrase_for, speak_html

st.set_page_config(page_title="Rupee Reader", page_icon="💵", layout="centered")

CSS = """
<style>
.rr-hero {
    background: linear-gradient(135deg, #1f3a5f 0%, #2d6a7f 100%);
    padding: 1.6rem 1.8rem;
    border-radius: 14px;
    color: #ffffff;
    margin-bottom: 1.1rem;
}
.rr-hero h1 { margin: 0; font-size: 2.1rem; color: #ffffff; }
.rr-hero p  { margin: .35rem 0 0; font-size: 1.02rem; opacity: .92; }
.rr-result {
    background: #f4f8fb;
    border: 2px solid #2d6a7f;
    border-radius: 14px;
    padding: 1.4rem 1.6rem;
    text-align: center;
}
.rr-denom { font-size: 4rem; font-weight: 800; color: #1f3a5f; line-height: 1.05; }
.rr-label { font-size: .95rem; letter-spacing: .09em; text-transform: uppercase; color: #52708a; }
.rr-speak { font-size: 1.25rem; color: #1f3a5f; margin-top: .5rem; }
</style>
"""


@st.cache_resource
def get_predictor():
    return Predictor()


def hero():
    st.markdown(
        """
        <div class="rr-hero">
            <h1>💵 Rupee Reader</h1>
            <p>AI-Based Indian Currency Recognition &amp; Voice Assistant</p>
        </div>
        """,
        unsafe_allow_html=True,
    )


def prototype_banner(synthetic: bool, info: dict):
    if synthetic:
        n = info.get("num_training_images", "?")
        acc = info.get("final_val_accuracy")
        acc_txt = f"{acc * 100:.1f}%" if isinstance(acc, (int, float)) else "n/a"
        st.warning(
            "🔬 **PROTOTYPE / DEMO MODE — synthetic training data**\n\n"
            f"The MobileNetV2 classifier in this app was genuinely trained "
            f"({n} images, validation accuracy {acc_txt}), but it was trained on "
            "**synthetic placeholder cards generated by this project**, not on "
            "photographs of real Indian banknotes. It demonstrates the complete "
            "pipeline and classifies those synthetic demo cards. It is **not** "
            "validated on real currency and should not be relied on to identify "
            "real notes. To train on real data, see `dataset/README.md`."
        )
    else:
        st.info(
            "This model was trained on your own image set. Real-world accuracy "
            "depends on dataset size and variety — treat it as a student "
            "prototype."
        )


def setup_screen():
    hero()
    st.error(
        "**No trained model found yet.** One step and the demo is live — no "
        "dataset and no physical currency notes needed."
    )
    st.markdown(
        "Click the button below (or run `python setup_demo.py` in a terminal). "
        "It generates a synthetic demo dataset and trains the MobileNetV2 "
        "classifier on it. Takes roughly **1–3 minutes** on a laptop CPU."
    )

    if st.button("⚙️ Generate demo data & train model", type="primary"):
        from utils.synthetic import generate_dataset, generate_samples
        import train

        with st.status("Setting up the demo…", expanded=True) as status:
            st.write("Generating synthetic demo dataset…")
            n = generate_dataset("dataset", per_class=40)
            st.write(f"Wrote {n} images to `dataset/`")

            st.write("Generating held-out sample images…")
            generate_samples("sample_images")

            st.write("Training MobileNetV2 classifier (this is the slow part)…")
            train.main(epochs=6)

            status.update(label="Demo ready", state="complete")

        st.cache_resource.clear()
        st.success("Model trained. Reloading…")
        st.rerun()

    st.divider()
    st.caption(
        "Disclaimer: This project is an educational accessibility prototype and "
        "is not a currency authentication or counterfeit detection system."
    )


def pick_image():
    st.subheader("1 · Provide an image")
    tab_sample, tab_upload, tab_camera = st.tabs(
        ["🧪 Demo samples", "📁 Upload image", "📷 Camera"]
    )

    image_file = None

    with tab_sample:
        samples = sorted(glob.glob(os.path.join("sample_images", "sample_demo_*.png")))
        if samples:
            st.caption(
                "Synthetic demo cards, held out from training. Use these to "
                "demonstrate the pipeline without any real currency."
            )
            choice = st.selectbox(
                "Pick a demo card",
                samples,
                format_func=lambda p: "₹" + os.path.basename(p).split("_")[-1].replace(".png", ""),
            )
            if choice:
                image_file = choice
        else:
            st.caption("No sample images found. Run `python setup_demo.py` to create them.")

    with tab_upload:
        uploaded = st.file_uploader(
            "Upload an image", type=["jpg", "jpeg", "png"], label_visibility="visible"
        )
        if uploaded is not None:
            image_file = uploaded

    with tab_camera:
        captured = st.camera_input("Take a photo")
        if captured is not None:
            image_file = captured

    return image_file


def show_result(predictor, image_file):
    label, confidence, all_scores = predictor.predict(image_file)
    phrase = phrase_for(label)

    st.markdown(
        f"""
        <div class="rr-result">
            <div class="rr-label">Detected Currency</div>
            <div class="rr-denom">₹{label}</div>
            <div class="rr-label">Confidence {confidence * 100:.1f}%</div>
            <div class="rr-speak">🔊 “{phrase}”</div>
        </div>
        """,
        unsafe_allow_html=True,
    )

    st.progress(min(max(confidence, 0.0), 1.0))

    # Auto-speak for accessibility: the result is announced without needing
    # to find and press a button.
    components.html(speak_html(phrase), height=0)

    col_a, col_b = st.columns(2)
    with col_a:
        if st.button("🔊 Speak again", use_container_width=True):
            components.html(speak_html(phrase), height=0)
    with col_b:
        with st.popover("📊 All class scores", use_container_width=True):
            for name, score in all_scores:
                st.write(f"₹{name} — {score * 100:.1f}%")

    if predictor.synthetic:
        st.caption(
            "🔬 Prototype output — classifier trained on synthetic demo images, "
            "not validated on real banknotes."
        )


def main():
    st.markdown(CSS, unsafe_allow_html=True)

    if not model_available():
        setup_screen()
        return

    hero()

    st.info(
        "♿ **Accessibility purpose:** Rupee Reader is built to help visually "
        "impaired and low-vision users identify currency denominations by "
        "sound. Choose an image, press **Recognize Currency**, and the "
        "denomination is announced aloud automatically."
    )

    predictor = get_predictor()
    prototype_banner(predictor.synthetic, load_model_info())

    image_file = pick_image()

    if image_file is not None:
        st.image(image_file, caption="Selected image", use_container_width=True)

        st.subheader("2 · Recognize")
        if st.button("🔍 Recognize Currency", type="primary", use_container_width=True):
            with st.spinner("Preprocessing image and running the classifier…"):
                show_result(predictor, image_file)
    else:
        st.caption("Pick a demo sample, upload an image, or use the camera to begin.")

    with st.expander("ℹ️ How it works"):
        st.markdown(
            """
            ```
            Image (sample / upload / camera)
                    ↓
            Preprocessing — resize to 224×224, RGB
                    ↓
            MobileNetV2 (frozen ImageNet base) + trained dense head
                    ↓
            Softmax over 6 denominations
                    ↓
            Denomination + confidence score
                    ↓
            Voice output (browser speech synthesis)
            ```
            """
        )

    st.divider()
    st.caption(
        "Disclaimer: This project is an educational accessibility prototype and "
        "is not a currency authentication or counterfeit detection system. It "
        "does not verify authenticity, does not detect counterfeits, and makes "
        "no accuracy guarantee."
    )


if __name__ == "__main__":
    main()
